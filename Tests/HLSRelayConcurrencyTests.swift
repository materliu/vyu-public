import Network
import XCTest
@testable import VYu

@MainActor final class HLSRelayConcurrencyTests: XCTestCase {
    func testIdlePreconnectionsDoNotRejectConcurrentVideoAndAudioRequests() async throws {
        let base = URL(string: "http://127.0.0.1:8765")!
        let configuration = URLSessionConfiguration.ephemeral
        configuration.httpCookieStorage = nil
        configuration.urlCredentialStorage = nil
        configuration.httpMaximumConnectionsPerHost = 12
        configuration.timeoutIntervalForRequest = 30
        configuration.timeoutIntervalForResource = 60
        let session = URLSession(configuration: configuration)
        defer { session.invalidateAndCancel() }
        let health: (Data, URLResponse)
        do { health = try await session.data(from: base.appendingPathComponent("__health")) }
        catch let error as URLError where error.code == .cannotConnectToHost {
            throw XCTSkip("Start generated-media fixtures before running relay concurrency tests.")
        }
        XCTAssertEqual((health.1 as? HTTPURLResponse)?.statusCode, 200)
        let state = try XCTUnwrap(JSONSerialization.jsonObject(with: health.0) as? [String: Any])
        XCTAssertEqual(state["ready"] as? Bool, true)
        XCTAssertEqual(state["offline"] as? Bool, false)

        let source = base.appendingPathComponent("hls-relay-wire/complete/index.m3u8")
        let candidate = MediaCandidate(url: source, pageURL: base, frameURL: base,
            title: "Synthetic concurrent transport", kind: .hls, source: "fixture")
        let relay = HLSDownloadRelay(candidate: candidate, cookies: [])
        defer { relay.stop() }
        let local = try await relay.start(sourceURL: source)
        let (manifest, response) = try await session.data(from: local)
        XCTAssertEqual((response as? HTTPURLResponse)?.statusCode, 200)
        let segmentLine = String(decoding: manifest, as: UTF8.self).split(separator: "\n").first { !$0.hasPrefix("#") }
        let segment = try XCTUnwrap(segmentLine.flatMap { URL(string: String($0)) })
        XCTAssertEqual(segment.host, "127.0.0.1")
        let port = try XCTUnwrap(local.port.flatMap { UInt16(exactly: $0) }.flatMap(NWEndpoint.Port.init(rawValue:)))

        // Reproduce AVFoundation's idle/preconnected sockets. The old limit
        // counted these as four active transfers and reset all following GETs.
        let idle = (0..<4).map { _ in NWConnection(host: "127.0.0.1", port: port, using: .tcp) }
        defer { idle.forEach { $0.cancel() } }
        for connection in idle { connection.start(queue: .global(qos: .userInitiated)) }
        let deadline = Date().addingTimeInterval(10)
        while !idle.allSatisfy({ if case .ready = $0.state { return true }; return false }), Date() < deadline {
            try await Task.sleep(for: .milliseconds(100))
        }
        XCTAssertTrue(idle.allSatisfy { if case .ready = $0.state { return true }; return false })

        let responses = try await withThrowingTaskGroup(of: (Data, Int).self) { group in
            for _ in 0..<10 {
                group.addTask {
                    let (body, response) = try await session.data(from: segment)
                    return (body, (response as? HTTPURLResponse)?.statusCode ?? 0)
                }
            }
            var results: [(Data, Int)] = []
            for try await result in group { results.append(result) }
            return results
        }
        XCTAssertEqual(responses.count, 10)
        let expected = Data((0..<131_072).map { UInt8($0 % 256) })
        for (body, status) in responses {
            XCTAssertEqual(status, 200)
            XCTAssertEqual(body, expected, "Every queued transfer must preserve all generated bytes.")
        }
        XCTAssertNil(relay.failure)
    }
}
